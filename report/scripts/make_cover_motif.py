"""Generate the isometric-cube motif for the cover (report/figures/cover_motif.tex).

Deterministic (fixed seed). Coordinates are millimetres from the page's top-left corner, y pointing up (negative = down).
Run:  python report/scripts/make_cover_motif.py
"""
from __future__ import annotations

import math
import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "figures/cover_motif.tex"
rng = random.Random(7)
lines: list[str] = []


def shrink(pts, k):
    cx = sum(p[0] for p in pts) / len(pts)
    cy = sum(p[1] for p in pts) / len(pts)
    return [(cx + (x - cx) * k, cy + (y - cy) * k) for x, y in pts]


def face(pts, style, k):
    p = " -- ".join(f"({x:.2f},{y:.2f})" for x, y in shrink(pts, k))
    lines.append(f"\\path[{style}] {p} -- cycle;")


def cube(cx, cy, s, accent, k):
    c = s * math.sqrt(3) / 2
    top = [(cx, cy), (cx + c, cy + s / 2), (cx, cy + s), (cx - c, cy + s / 2)]
    left = [(cx, cy), (cx - c, cy + s / 2), (cx - c, cy - s / 2), (cx, cy - s)]
    right = [(cx, cy), (cx + c, cy + s / 2), (cx + c, cy - s / 2), (cx, cy - s)]
    face(left, "cleft", k)
    face(right, "cright", k)
    face(top, "caccent" if accent else "ctop", k)


def field(s, keep, x_range, y_rows, y0, accent_p, k):
    c = s * math.sqrt(3) / 2
    for j in range(y_rows):
        cy = y0 - j * 1.5 * s
        off = c if j % 2 else 0
        i = -1
        while True:
            cx = i * 2 * c + off
            if cx - c > x_range[1]:
                break
            i += 1
            if cx + c < x_range[0]:
                continue
            p = keep(cx, cy)
            if p > 0 and rng.random() < p:
                cube(cx, cy, s, rng.random() < accent_p, k)


# --- large field, top of page: dense near the top edge, thinning towards a diagonal boundary
def keep_top(cx, cy):
    limit = -(118 - 0.33 * cx)         # lowest allowed cube bottom (mm); higher on the right
    if cx < 30:
        limit -= 26                    # tail running down the left edge
    margin = (cy - 19) - limit         # cube bottom minus the limit
    if margin < 0:
        return 0
    return 0.6 if margin < 14 else 0.97


lines.append("% --- large cube field (top)")
field(s=19, keep=keep_top, x_range=(-10, 220), y_rows=7, y0=-4, accent_p=0.2, k=0.9)


# --- small cluster, bottom-left corner
def keep_bottom(cx, cy):
    d = cx * 0.85 + (cy + 297) * 1.0
    if d > 64:
        return 0
    return 0.55 if d > 44 else 0.95


lines.append("% --- small cube cluster (bottom left)")
field(s=10.5, keep=keep_bottom, x_range=(-8, 90), y_rows=9, y0=-232, accent_p=0.2, k=0.88)

OUT.write_text("% generated by scripts/make_cover_motif.py; do not edit by hand\n" + "\n".join(lines) + "\n")
print(f"wrote {OUT} ({len(lines)} lines)")
