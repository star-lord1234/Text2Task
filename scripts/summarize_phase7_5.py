"""Builds results/phase7_5/COMPARISON.md from the saved run summaries (no hand-typed numbers)."""
import json
from pathlib import Path

R = Path(__file__).resolve().parents[1] / "results/phase7_5"
PRESETS = ["neural_only", "neural_plus_linker", "refined", "hybrid", "rule_only"]
FIX = {"live_battery_v1": "Development battery (24 cases; used while building)", "live_scenarios_new": "New scenarios (34 cases; written before the code, then used to find bugs)",
       "live_scenarios_holdout": "Holdout (30 cases; written after the first comparison run and before the fixes it motivated; executed only after those fixes)"}


def table(summary: dict, fx: str, group: str = "ALL") -> list[str]:
    n = summary[fx][PRESETS[0]][group]["cases"]
    lines = [f"| configuration | passed (strict) | task recall | owner acc. | due acc. | status acc. | edge recall | false tasks | false edges |", "|---|---|---|---|---|---|---|---|---|"]
    f = lambda v: "n/a" if v is None else f"{v:.2f}"
    for p in PRESETS:
        if p not in summary[fx]:
            continue
        s = summary[fx][p][group]
        lines.append(f"| {p} | {s['passed_strict']}/{n} | {f(s['task_recall'])} | {f(s['owner_accuracy'])} | {f(s['due_accuracy'])} | {f(s['status_accuracy'])} | "
                     f"{s['edge_recall'] if s['edge_recall'] is None else round(s['edge_recall'] * s['expected_edges'])}/{s['expected_edges']} | {s['spurious_tasks']} | {s['spurious_edges']} |")
    return lines


def main() -> None:
    final = json.loads((R / "summary.json").read_text())
    first = json.loads((R / "first_run/summary.json").read_text())
    out = ["# Phase 7.5 comparison tables (generated by scripts/summarize_phase7_5.py from results/phase7_5/*.json)", "",
           "A simulated reviewer accepts every actionable proposal, so 'false tasks' and 'false edges' are what an accept-everything reviewer would get. "
           "Fixtures are developer-written short chat messages and mirror the author's own phrasing; treat the numbers as a functional comparison, not accuracy.", ""]
    for fx, title in FIX.items():
        out += [f"## {title} - final code", ""] + table(final, fx) + [""]
    out += ["## First run (before any refinement bug fixes), development + new scenarios", ""]
    for fx in ("live_battery_v1", "live_scenarios_new"):
        out += [f"### {FIX[fx]}", ""] + table(first, fx) + [""]
    hl = R / "holdout_first_look/summary.json"
    if hl.exists():
        out += ["## Holdout, very first execution (before one late precision fix to the grammar stage)", ""] + table(json.loads(hl.read_text()), "live_scenarios_holdout") + [""]
    for fx in ("live_battery_v1", "live_scenarios_new", "live_scenarios_holdout"):
        out += [f"## Per group, hybrid vs neural_only: {fx}", "", "| group | n | neural_only strict | hybrid strict | neural_only false tasks | hybrid false tasks |", "|---|---|---|---|---|---|"]
        for g in final[fx]["hybrid"]:
            a, b = final[fx]["neural_only"][g], final[fx]["hybrid"][g]
            out.append(f"| {g} | {b['cases']} | {a['passed_strict']} | {b['passed_strict']} | {a['spurious_tasks']} | {b['spurious_tasks']} |")
        out.append("")
    sv = R / "silver_validation.json"
    if sv.exists():
        d = json.loads(sv.read_text())
        out += ["## Entity agreement with provisional SILVER labels on real emails (validation, read-only)", "", d["scope"], "",
                "| configuration | TASK P / R / F1 | PERSON F1 | TEMPORAL F1 | ALL P / R / F1 | span origins |", "|---|---|---|---|---|---|"]
        for p, v in d["results"].items():
            s = v["scores"]
            out.append(f"| {p} | {s['TASK']['precision']:.3f} / {s['TASK']['recall']:.3f} / {s['TASK']['f1']:.3f} | {s['PERSON']['f1']:.3f} | {s['TEMPORAL']['f1']:.3f} | "
                       f"{s['ALL']['precision']:.3f} / {s['ALL']['recall']:.3f} / {s['ALL']['f1']:.3f} | {v['span_origins']} |")
        out.append("")
    (R / "COMPARISON.md").write_text("\n".join(out))
    print("\n".join(out[:60]))


if __name__ == "__main__":
    main()
